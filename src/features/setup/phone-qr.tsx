"use client";

import QRCode from "qrcode";
import { useEffect, useState } from "react";
import { useSigninLink } from "./use-signin-link";

/**
 * Connect fix 2 (board approved 24 Nov): on a computer, a quiet "Scan to finish on your phone",
 * where Instagram is usually already signed in. The code carries the one-time sign-in link to
 * this setup step (10 minutes, one use), so the phone opens it signed in.
 */
export function PhoneQr() {
  const link = useSigninLink();
  const [svg, setSvg] = useState<{ for: string; svg: string } | null>(null);
  useEffect(() => {
    if (!link) return;
    let live = true;
    QRCode.toString(link, { type: "svg", margin: 1, errorCorrectionLevel: "M" })
      .then((s) => {
        if (live) setSvg({ for: link, svg: s });
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [link]);
  const ready = svg && svg.for === link;
  return (
    <div className="border-line-strong hidden items-center gap-3 rounded-xl border border-dashed px-3 py-2.5 md:flex">
      <div
        role="img"
        aria-label="QR code that opens this step on your phone"
        className="size-[72px] shrink-0 rounded-md bg-white p-1 [&_svg]:h-full [&_svg]:w-full"
        // Generated by the qrcode library from our own link: no user HTML.
        dangerouslySetInnerHTML={ready ? { __html: svg.svg } : undefined}
      />
      <p className="flex min-w-[200px] flex-1 flex-col gap-0.5 text-[13px]">
        <b className="font-semibold">Instagram on your phone? Scan to finish there.</b>
        <span className="text-ink-2">
          You’re usually already signed in on your phone, so it’s faster. You’ll land on this step.
        </span>
      </p>
    </div>
  );
}

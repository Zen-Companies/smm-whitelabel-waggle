"use client";

import QRCode from "qrcode";
import { SidePanel } from "@/components/app/side-panel";
import { EmptySpot } from "@/components/app/empty-spot";
import { useActionState, useState } from "react";
import { CopyButton } from "@/components/app/copy-button";
import { PlatformMark } from "@/components/app/platform-mark";
import { Button } from "@/components/ui/button";
import type { ChatFlow } from "@/lib/social/types";
import { changeFlow, type AutomationFormState } from "./actions";
import type { AutomationAccount } from "./comment-dm-form";
import { FlowForm } from "./flows-section";

export type LinkFlow = ChatFlow & { qrSvg: string };

/**
 * Links and QR codes (T77d, design "Automations · Links and QR"): an ig.me / m.me link that
 * opens a chat with the business and starts a chat flow, with a QR code to print.
 */
export function LinksSection({
  links,
  accounts,
  canEdit,
}: {
  links: LinkFlow[];
  accounts: AutomationAccount[];
  canEdit: boolean;
}) {
  const [open, setOpen] = useState(false);
  return (
    <div className="flex flex-col gap-5">
      {links.length === 0 && <EmptySpot>No links yet. A link or QR code opens a chat with you and starts a short conversation.</EmptySpot>}
      {links.length > 0 && (
        <ul className="card divide-line flex flex-col divide-y">
          {links.map((l) => (
            <LinkRow key={l.id} l={l} canEdit={canEdit} />
          ))}
        </ul>
      )}
      {canEdit && !open && (
        <Button type="button" variant="primary" className="self-start" onClick={() => setOpen(true)} disabled={!accounts.length}>
          New link
        </Button>
      )}
      {canEdit && open && accounts.length > 0 && (
        <SidePanel label="New link" onClose={() => setOpen(false)}>
          <p className="text-ink-2 text-sm">
            Opens a chat with you and starts a short conversation. Print the QR code on tables, flyers and receipts.
          </p>
          <FlowForm mode="link" accounts={accounts} onDone={() => setOpen(false)} />
        </SidePanel>
      )}
      {!accounts.length && <p className="meta">Connect Instagram or Facebook first.</p>}
      <p className="meta">Instagram and Facebook conversations can only continue within 24 hours of the person&apos;s last message.</p>
    </div>
  );
}

function LinkRow({ l, canEdit }: { l: LinkFlow; canEdit: boolean }) {
  const [state, act, pending] = useActionState<AutomationFormState, FormData>(changeFlow, {});
  const [confirm, setConfirm] = useState(false);
  const file = l.name.replace(/[^\w-]+/g, "-").toLowerCase() || "waggle-link";
  const download = async (kind: "png" | "svg") => {
    const href =
      kind === "png"
        ? await QRCode.toDataURL(l.description, { width: 1024, margin: 2 })
        : `data:image/svg+xml;charset=utf-8,${encodeURIComponent(l.qrSvg)}`;
    const a = document.createElement("a");
    a.href = href;
    a.download = `${file}-qr.${kind}`;
    a.click();
  };
  const op = (value: string, label: string, danger = false) => (
    <form action={act}>
      <input type="hidden" name="id" value={l.id} />
      <input type="hidden" name="op" value={value} />
      <Button type="submit" variant="quiet" className={danger ? "text-danger" : undefined} disabled={pending}>
        {label}
      </Button>
    </form>
  );
  return (
    <li className="flex flex-wrap items-start gap-4 px-4 py-4">
      <span
        role="img"
        aria-label={`QR code for ${l.description}`}
        className="size-28 shrink-0 rounded-xl bg-white p-1.5 [&_svg]:h-full [&_svg]:w-full"
        // Generated by the qrcode library from our own link: no user HTML.
        dangerouslySetInnerHTML={{ __html: l.qrSvg }}
      />
      <span className="flex min-w-0 flex-1 flex-col gap-1.5">
        <span className="flex items-center gap-2">
          <PlatformMark platform={l.platform} size={22} />
          <b className="font-semibold">{l.name}</b>
          <span
            className={`rounded-full px-2.5 py-0.5 text-xs font-semibold ${l.status === "active" ? "bg-success-soft text-success" : "bg-subtle text-ink-2"}`}
          >
            {l.status === "active" ? "On" : l.status === "paused" ? "Paused" : "Draft"}
          </span>
        </span>
        <span className="font-mono text-sm break-all">{l.description}</span>
        <span className="meta">{l.started} started · {l.completed} finished</span>
        <span className="flex flex-wrap items-center gap-1">
          <CopyButton text={l.description} label="Copy link" />
          <Button type="button" variant="quiet" onClick={() => download("png")}>
            QR (PNG)
          </Button>
          <Button type="button" variant="quiet" onClick={() => download("svg")}>
            QR (SVG)
          </Button>
          {canEdit && (l.status === "active" ? op("off", "Pause") : op("on", "Turn on"))}
          {canEdit &&
            (confirm ? (
              <>
                {op("delete", "Delete for good", true)}
                <Button type="button" variant="quiet" onClick={() => setConfirm(false)}>
                  Keep
                </Button>
              </>
            ) : (
              <Button type="button" variant="quiet" onClick={() => setConfirm(true)}>
                Delete
              </Button>
            ))}
        </span>
        {state.error && (
          <span role="alert" className="text-danger text-sm">
            {state.error}
          </span>
        )}
      </span>
    </li>
  );
}
